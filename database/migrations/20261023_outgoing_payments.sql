-- Tablas aditivas para registrar egresos a proveedores y nómina.
-- No modifica las tablas de facturas/pagos existentes ni carga datos ficticios.
-- Ejecutar únicamente después de revisar el esquema y respaldar la base objetivo.

CREATE TABLE IF NOT EXISTS finanzas.obligacion_egreso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo VARCHAR(60) NOT NULL UNIQUE,
  origen VARCHAR(12) NOT NULL CHECK (origen IN ('PROVEEDOR', 'NOMINA')),
  referencia_origen VARCHAR(100),
  beneficiario VARCHAR(160) NOT NULL,
  monto_original NUMERIC(14, 2) NOT NULL CHECK (monto_original > 0),
  saldo_pendiente NUMERIC(14, 2) NOT NULL CHECK (
    saldo_pendiente >= 0 AND saldo_pendiente <= monto_original
  ),
  fecha_vencimiento DATE NOT NULL,
  estado VARCHAR(10) NOT NULL CHECK (estado IN ('PENDIENTE', 'PARCIAL', 'PAGADA')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (
    (saldo_pendiente = monto_original AND estado = 'PENDIENTE')
    OR (saldo_pendiente > 0 AND saldo_pendiente < monto_original AND estado = 'PARCIAL')
    OR (saldo_pendiente = 0 AND estado = 'PAGADA')
  )
);

CREATE TABLE IF NOT EXISTS finanzas.movimiento_egreso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  obligacion_id BIGINT NOT NULL REFERENCES finanzas.obligacion_egreso(id),
  monto NUMERIC(14, 2) NOT NULL CHECK (monto > 0),
  fecha_pago DATE NOT NULL,
  idempotency_key UUID NOT NULL UNIQUE,
  saldo_anterior NUMERIC(14, 2) NOT NULL CHECK (saldo_anterior > 0),
  saldo_restante NUMERIC(14, 2) NOT NULL CHECK (saldo_restante >= 0),
  descripcion VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (monto + saldo_restante = saldo_anterior)
);

CREATE TABLE IF NOT EXISTS finanzas.pago_egreso (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  movimiento_id BIGINT NOT NULL UNIQUE REFERENCES finanzas.movimiento_egreso(id),
  obligacion_id BIGINT NOT NULL REFERENCES finanzas.obligacion_egreso(id),
  metodo VARCHAR(50) NOT NULL,
  referencia_bancaria VARCHAR(100),
  observaciones VARCHAR(500)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pago_egreso_referencia_bancaria
  ON finanzas.pago_egreso (referencia_bancaria)
  WHERE referencia_bancaria IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_obligacion_egreso_vencimiento
  ON finanzas.obligacion_egreso (fecha_vencimiento)
  WHERE saldo_pendiente > 0;

CREATE INDEX IF NOT EXISTS idx_movimiento_egreso_fecha
  ON finanzas.movimiento_egreso (fecha_pago DESC);
